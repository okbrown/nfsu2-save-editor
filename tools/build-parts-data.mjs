// Builds js/parts-data.js, the editor's built-in parts table, from the game's own data.
//
//   node tools/build-parts-data.mjs "<NFSU2 folder>/GLOBAL/GlobalB.lzc"   (or an unpacked GLOBALB.BUN)
//
// Keeps only what the Visuals menus read: each part's ID, name, type, level, variant, group and colour,
// the attributes the editor uses, the slot-to-group compatibility tables, and the car records' names and
// factory paints. No models, textures or other game content.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
require('../js/visual-editor.js');
const V = globalThis.NFSU2Visual;

const source = process.argv[2];
if (!source) {
  console.error('usage: node tools/build-parts-data.mjs <GlobalB.lzc or GLOBALB.BUN>');
  process.exit(1);
}
const catalog = V.parseGameData(new Uint8Array(readFileSync(source)));

// The attributes the editor reads (js/visual-editor.js): paint category / rim brand, slots a part hides,
// under-hood part, carbon, the three car-family exclusions, rim wheel class and rim size.
const ATTRIBUTES = [0xebb03e66, 0xe80a3b62, ...['HOODUNDER', 'CARBONFIBRE', 'EXCLUDE_UG1', 'EXCLUDE_UG2', 'EXCLUDE_SUV'].map(V.gameHash),
  0xce7d8db5, 0xeb0101e2];

const groups = [...new Set(catalog.parts.map((p) => p.group))];
const hex = (n) => '0x' + (n >>> 0).toString(16);
const str = (s) => JSON.stringify(s);
const part = (p) => {
  const attrs = ATTRIBUTES.map((k, i) => (p.attributes.has(k) ? `${i}:[${p.attributes.get(k).map(hex).join(',')}]` : '')).filter(Boolean);
  return `[${hex(p.hash)},${str(p.name)},${p.type},${p.level},${p.variant},${groups.indexOf(p.group)},${str(p.color)}${attrs.length ? `,{${attrs.join(',')}}` : ''}]`;
};

const out = `/*
 * Built-in parts table for the Visuals menus, generated by tools/build-parts-data.mjs from the game's
 * GLOBAL\\GlobalB.lzc (visual database chunks 0x34603-0x3460C and the car records of chunk 0x34600).
 * Identifiers, names and compatibility only. A game data file the player loads takes precedence.
 *
 * parts: [hash, name, type, level, variant, group index, colour, {attribute index: [values]}]
 */
(function (root) {
  root.NFSU2PartsData = {
    attributes: [${ATTRIBUTES.map(hex).join(', ')}],
    groups: [${groups.map(hex).join(',')}],
    cars: [${catalog.cars.map((c) => `[${hex(c.hash)},${str(c.name)},${hex(c.stockPaint)}]`).join(',')}],
    defaults: [${catalog.defaults.map(hex).join(',')}],
    overrides: [${[...catalog.overrides].map(([key, [a, b]]) => { const [car, slot] = key.split(':').map(Number); return `[${hex(car)},${slot},${hex(a)},${hex(b)}]`; }).join(',')}],
    parts: [
${catalog.parts.map(part).join(',\n')}
    ],
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;
writeFileSync(new URL('../js/parts-data.js', import.meta.url), out);
console.log(`js/parts-data.js: ${catalog.parts.length} parts, ${catalog.cars.length} cars, ${(out.length / 1024).toFixed(0)} KB`);
